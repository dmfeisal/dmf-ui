// M17: presets change the theme only. For every parity case on /internal/shadcn-parity/, the DMF side is measured under
// the dmf preset and under each other preset. Colours, the corner radius and the font are theme properties and may
// differ; any other measured difference (size, spacing, font size and weight, line height, border width) is a structural
// change and must be recorded in docs/DMF-UI-PRESET-THEME.json. The scenario fails when the set of such differences
// changes. To accept a change: DMF_UI_PRESET_WRITE=1 npm run test:dmf-ui:docs (writes the record).
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {measure} from './dmf-ui-shadcn-parity.mjs';

const root=fileURLToPath(new URL('../../',import.meta.url));
export const presets=['cb-ui','hui','qdi','portfolio'];
export const themeProperties=new Set(['color','backgroundColor','borderTopColor','borderTopLeftRadius']);
const recordPath=`${root}docs/DMF-UI-PRESET-THEME.json`;

export async function run({page,baseURL,navigate,settle,resetBrowser}){
 const assert=(value,message)=>{if(!value)throw new Error(message);};
 await resetBrowser();
 await navigate(`${baseURL}/internal/shadcn-parity/`);await settle();
 const setPreset=preset=>page.evaluate(preset=>{document.querySelectorAll('[data-parity-side=dmf]').forEach(e=>{e.dataset.system=preset;});},preset);
 await setPreset('dmf');
 const base=Object.fromEntries((await measure(page)).filter(r=>r.dmf).map(r=>[r.id,r.dmf]));
 assert(Object.keys(base).length>0,'No parity cases were measured under the dmf preset');
 const differences={};
 for(const preset of presets){
  await setPreset(preset);await settle();
  const results=await measure(page);
  const out={};
  for(const r of results){
   if(!r.dmf||!base[r.id])continue;
   // Width follows the preset's font (text, and an input's intrinsic size), a theme property, so it is not compared here;
   // height, padding, gaps, font size and border width are.
   const props=Object.keys(base[r.id]).filter(p=>!themeProperties.has(p)&&p!=='width'&&r.dmf[p]!==base[r.id][p]&&!(typeof base[r.id][p]==='number'&&Math.abs(r.dmf[p]-base[r.id][p])<=0.5));
   if(props.length)out[r.id]=props;
  }
  differences[preset]=out;
 }
 await setPreset('dmf');
 const keys=Object.entries(differences).flatMap(([preset,cases])=>Object.entries(cases).flatMap(([id,props])=>props.map(p=>`${preset} ${id} ${p}`))).sort();
 const artifacts=`${root}.dmf-ui-test-results`;await mkdir(artifacts,{recursive:true});
 const record={about:'Structural differences between the dmf preset and each other preset, for the parity cases (M17). Theme properties (colours, corner radius) are excluded. Generated by tests/browser/dmf-ui-preset-theme.mjs.',presets,themeProperties:[...themeProperties],differences};
 await writeFile(`${artifacts}/preset-theme.json`,JSON.stringify(record,null,1)+'\n');
 if(process.env.DMF_UI_PRESET_WRITE==='1'){await writeFile(recordPath,JSON.stringify(record,null,1)+'\n');console.log(`Wrote ${recordPath}: ${keys.length} structural differences`);return;}
 const committed=JSON.parse(await readFile(recordPath,'utf8'));
 const committedKeys=Object.entries(committed.differences).flatMap(([preset,cases])=>Object.entries(cases).flatMap(([id,props])=>props.map(p=>`${preset} ${id} ${p}`))).sort();
 const added=keys.filter(k=>!committedKeys.includes(k)),removed=committedKeys.filter(k=>!keys.includes(k));
 assert(!added.length&&!removed.length,`Preset structure changed (new: ${added.slice(0,10).join('; ')}; gone: ${removed.slice(0,10).join('; ')}). Review, then run DMF_UI_PRESET_WRITE=1 to accept.`);
 console.log(`PASS preset theme: ${Object.keys(base).length} cases under ${presets.length} presets; ${keys.length} recorded structural differences unchanged`);
}
